#pragma once

#include <cstdint>
#include <vector>

#include <glm/glm.hpp>

// Одна вершина в вершинном буфере: позиция, нормаль и текстурные координаты (32 байта).
struct Vertex {
	glm::vec3 position;
	glm::vec3 normal;
	glm::vec2 uv;
};

// Сетка треугольников: вершины + индексы (каждые 3 индекса -- один треугольник).
struct Mesh {
	std::vector<Vertex> vertices;
	std::vector<uint32_t> indices;
};

// Вариант 4: усечённый правильный тетраэдр (8 граней, у каждой свои вершины и нормали).
// Текстурные координаты получены проекцией каждой грани на её собственную плоскость,
// поэтому плотность текстуры одинакова на треугольниках и шестиугольниках.
Mesh makeTruncatedTetrahedron();

// Квадрат 1x1 в плоскости XZ (нормаль +Y), текстурные координаты от 0 до 1.
// Из него делаются пол и стена: масштабом и поворотом при отрисовке.
Mesh makeQuad();
